'use strict';
// ГЛОБАЛНА ФУНКЦИЯ „parseJson“ — едното място, в което се решава какво значи „невалиден JSON“.
//
// Защо е глобална: `JSON.parse` хвърля, а почти всеки вход в add-on-а идва от файл, база или
// мрежа, където повреден запис е НОРМАЛЕН случай (прекъснат запис, ръчна редакция, стар файл).
// Досега всяко място увиваше `JSON.parse` в собствен `try` и връщаше различно нещо — `null`,
// `[]`, `{}`, текст, 400 или 500 — тоест един и същ вход се държеше различно според това кой
// модул го чете (DEF-67).
//
// Тук НЕ се хвърля: връща се резултат, а решението „400 за входа“ или „подразбиране за
// вътрешния запис“ остава у викащия, защото само той знае кой е входът. Така повреденият ред в
// дневника не събаря заявка, а невалидното тяло на заявка не влиза в базата.
//
//   const r = parseJson(raw)        // { ok: true, value } | { ok: false, error }
//   const v = parseJsonOr(raw, {})  // стойност или подразбирането, без проверка на `ok`
//
// Правилата, които не се разхлабват:
//   • никога не хвърля — при `undefined`, обект или празен текст връща `ok: false`;
//     входът иначе се привежда до текст точно както при самия `JSON.parse` (затова `Buffer`
//     и число се разчитат), за да не се промени поведението на заменените места;
//   • `error` е текстът на `SyntaxError`, за да влезе в съобщението на 400/500 — точката и
//     позицията са единственото, което помага на оператора;
//   • `parseJsonOr` връща подразбирането САМО при повреда: текстът `null` е валиден JSON и дава
//     `null`, тоест „стойността е null“ и „записът е повреден“ не се бъркат — за разликата се
//     ползва `parseJson`.

/** Разчита текст като JSON без хвърляне. @returns {{ok:boolean, value?:*, error?:string}} */
function parseJson(text) {
  try {
    return { ok: true, value: JSON.parse(text) };
  } catch (err) {
    return { ok: false, error: (err && err.message) || 'невалиден JSON' };
  }
}

/** Разчита текст като JSON и връща подразбиране при повреда. */
function parseJsonOr(text, fallback = null) {
  const result = parseJson(text);
  return result.ok ? result.value : fallback;
}

module.exports = { parseJson, parseJsonOr };
