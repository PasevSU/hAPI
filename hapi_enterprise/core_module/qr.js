'use strict';
// ГЛОБАЛНА ФУНКЦИЯ „qr“ — единственото място, което прави QR код.
//
// Защо е глобална: `server.js` (`/api/v1/p/<slug>/qr.svg`, полетата `qr`/`qrTarget` в
// отговорите, `api-registry`), `routes/portal-storage.js` (QR на папка) и
// `routes/portal-tokens.js` (QR на тайна връзка) искат ЕДНО и също нещо. Дотук три от тези
// четири места стигаха до `qr-svg` сами, тоест смяна на едно ниво корекция (размер на
// клетката, ниво на корекция, полета) минаваше през три файла.
//
// `qr-svg.js` остава рисуващият модул (матрица + SVG низ); тук е само ГЛОБАЛНИЯТ вход.
const qrSvg = require('../qr-svg');

module.exports.create = () => ({
  name: 'qr',
  fn: {
    /** SVG низ на QR код за подадения текст (адрес, токен, ключ). */
    svg: (text) => qrSvg.svg(text),
    /** Копие на настройките на рисуването — за отчет/диагностика, без да се пипа обектът. */
    options: () => ({ ...qrSvg.OPTIONS }),
  },
});
