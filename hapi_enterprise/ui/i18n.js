  const LANGS = Object.keys(DICT);

  function currentLang() {
    const ui = typeof window !== 'undefined' ? window.HapiUI : null;
    const lang = ui && typeof ui.getLang === 'function' ? ui.getLang() : '';
    if (lang && DICT[lang]) return lang;
    if (typeof document !== 'undefined' && document.documentElement && DICT[document.documentElement.lang]) {
      return document.documentElement.lang;
    }
    return 'bg';
  }

  /** Текст по ключ; непознат ключ се вижда като ключ, а не като празно място. */
  function t(key) {
    const lang = currentLang();
    if (DICT[lang] && DICT[lang][key] !== undefined) return DICT[lang][key];
    if (DICT.bg[key] !== undefined) return DICT.bg[key];
    return String(key);
  }

  const API = { t, DICT, LANGS, getLang: currentLang, has: (key) => DICT.bg[key] !== undefined };
  if (typeof window !== 'undefined') window.HapiI18n = API;
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
