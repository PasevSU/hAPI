'use strict';
// ВЕРСИЯ В АДРЕСА НА СТАТИЧНИТЕ РЕСУРСИ НА HTML СТРАНИЦА (DEF-87).
//
// Защо съществува: панелът иска 34 файла / 1044 KB, генераторът — своите. Без версия в
// адреса те не могат да се кешират (`no-store` при всяка заявка), а С версия не можеш да
// различиш обновяването на add-on-а от стария файл в браузъра. Затова версията влиза в
// адреса на самите ресурси, а не в заглавката: `app.js` → `app.js?v=<версия>`.
//
// Подменят се само ОТНОСИТЕЛНИТЕ имена (`tokens.css`, `app.js`) — външните адреси,
// `data:` и котвите остават както са. Файлът на диска не се пипа: подмяната е при сервиране,
// за да гледат `html-assets` и проверките за съществуващи файлове същата истина.
const REF = /"((?!https?:|data:|\/\/|#|\.\.?\/)[a-z0-9-]+\.(?:css|js))"/g;

/** Добавя `?v=<версия>` към относителните `src`/`href` в HTML. */
function versioned(html, version) {
  if (!version) return String(html);
  return String(html).replace(REF, (match, ref) => '"' + ref + '?v=' + encodeURIComponent(version) + '"');
}

module.exports = { versioned, REF };
