'use strict';
// QR КОД КАТО SVG — единственото място, което решава с какви параметри се рисува.
//
// Защо отделен модул: дотук едни и същи параметри стояха на две места (`server.js` за
// `/qr.svg` и `routes/portal-tokens.js` за кода на адреса с токен). Две копия на едно
// правило се разминават тихо — кодът на портала и кодът на токена щяха да изглеждат
// различно при първата промяна на клетка или поле.
//
// Параметрите са договор, не вкус: клетка 8, поле 4, мащабируем SVG (не фиксирани
// пиксели) — така кодът е четим на телефон и на печат, а размерът му се задава от CSS.
const OPTIONS = { cellSize: 8, margin: 4, scalable: true };

/** SVG на QR код за подадения текст. Ниво на корекция `M` (стандартно за адреси). */
function svg(text) {
  const code = require('./qrcode')(0, 'M');
  code.addData(String(text == null ? '' : text));
  code.make();
  return code.createSvgTag(OPTIONS);
}

module.exports = { svg, OPTIONS };
