'use strict';
const { stopChild } = require('./helpers.cjs');
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path'), { spawn } = require('node:child_process');
const ingress = '/api/hassio_ingress/test-token_123';
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'portal-ingress-'));
  const token = 'ingress-test-admin-secret-2026-a9f1', pub = 18199, adm = 18198;
  const projectFolder = path.join(dir, 'html-projects', 'ingress-site');
  fs.mkdirSync(projectFolder, { recursive: true });
  fs.writeFileSync(path.join(projectFolder, 'index.html'), '<h1>Ingress site works</h1>');
  const child = spawn(process.execPath, [path.join(__dirname, '../hapi_enterprise/server.js')], { env: { ...process.env, DATA_DIR: dir, ADMIN_TOKEN: token, PORT: String(pub), ADMIN_PORT: String(adm), INGRESS_MODE: 'true' }, stdio: 'pipe' });
  try {
    let ready = false;
    for (let i = 0; i < 70; i++) { try { if ((await fetch(`http://127.0.0.1:${pub}/health`)).ok) { ready = true; break } } catch { } await new Promise(r => setTimeout(r, 70)) }
    assert(ready, 'server startup');
    const get = (port, p, headers) => fetch(`http://127.0.0.1:${port}${p}`, { headers });
    const status = async (port, p, headers) => (await get(port, p, headers)).status;
    assert.equal(await status(pub, '/admin'), 404);
    assert.equal(await status(pub, '/admin/api/portals', { Authorization: 'Bearer ' + token }), 404);
    assert.equal(await status(pub, '/admin.js'), 404);
    assert.equal(await status(adm, '/api/v1/portals'), 404);
    assert.equal(await status(adm, '/admin'), 200);
    assert.equal(await status(adm, '/admin.js'), 200);
    // Control Center (ui/) живее в add-on пакета и се сервира САМО през ingress,
    // защото admin.html сочи към него с относителен линк.
    assert.equal(await status(pub, '/ui/index.html'), 404);
    assert.equal(await status(pub, '/hapi_enterprise/qrcode.js'), 404);
    assert.equal(await status(adm, '/ui/'), 200);
    assert.equal(await status(adm, '/ui/app.js'), 200);
    assert.equal(await status(adm, '/ui/styles.css'), 200);
    assert.equal(await status(adm, '/hapi_enterprise/report-manifest.js'), 200);
    const controlCenter = await get(adm, '/ui/');
    assert.equal(controlCenter.status, 200);
    assert.equal(controlCenter.headers.get('content-type'), 'text/html; charset=utf-8');
    assert.match(await controlCenter.text(), /Enterprise Control Center/);
    // Ingress listener без профили → администраторски права по подразбиране.
    assert.equal(await status(adm, '/admin/api/portals'), 200);
    assert.equal(await status(adm, '/admin/api/ingress-login'), 403);
    assert.equal(await status(pub, '/admin/api/ingress-login'), 404);
    assert.equal(await status(adm, '/admin/api/portals', { Authorization: 'Bearer ' + token }), 200);
    const ingressHeaders = { 'X-Ingress-Path': ingress };
    assert.equal(await status(adm, ingress + '/ui/', ingressHeaders), 200);
    assert.equal(await status(adm, ingress + '/ui/app.js', ingressHeaders), 200);
    assert.equal(await status(adm, ingress + '/hapi_enterprise/qrcode.js', ingressHeaders), 200);
    assert.equal(await status(adm, ingress + '/ui/../admin.js', ingressHeaders), 200);
    const adminPage = await get(adm, ingress + '/admin', ingressHeaders);
    assert.equal(adminPage.status, 200);
    const adminHtml = await adminPage.text();
    assert(adminHtml.includes('<title>hAPI Enterprise · Admin</title>'));
    assert(adminHtml.includes('<span class="brand-name">hAPI Enterprise</span>'));
    const adminScript = await get(adm, ingress + '/admin.js', ingressHeaders);
    assert.equal(adminScript.status, 200);
    const adminJs = await adminScript.text();
    assert(adminJs.includes('No portals have been created. Create the first portal using the form above.'));
    assert(adminJs.includes('Authentication succeeded. No portals have been created.'));
    assert(/event\.key\s*===\s*'Enter'/.test(adminJs));
    assert(!adminJs.includes('127.0.0.1:8099'));
    assert(/link\.href\s*=\s*adminPath\('\/site\/'/.test(adminJs));
    // Панелът НЕ издава и НЕ пази админ токен: под HA ролята идва от самоличността.
    assert(!adminHtml.includes('id="token"'));
    assert(!adminJs.includes("Authorization:'Bearer '+$('token')"));
    const loginSrc = fs.readFileSync(path.join(__dirname, '../hapi_enterprise/server.js'), 'utf8');
    const loginAt = loginSrc.indexOf('/admin/api/ingress-login');
    const loginBlock = loginSrc.slice(loginAt, loginSrc.indexOf('// Standalone', loginAt));
    assert(/req\.ingress === true/.test(loginBlock), 'ingress branch must exist');
    assert(!/token\s*:/.test(loginBlock), 'the HA ingress branch must never return a token');
    assert(/role,/.test(loginBlock), 'the HA ingress branch returns the resolved role');
    const doubleSlashAsset = await get(adm, ingress + '//admin.js', ingressHeaders);
    assert.equal(doubleSlashAsset.status, 200);
    assert.equal(doubleSlashAsset.headers.get('content-type'), 'application/javascript; charset=utf-8');
    const supervisorStyle = await get(adm, '//admin.js', ingressHeaders);
    assert.equal(supervisorStyle.status, 200);
    assert.equal(supervisorStyle.headers.get('content-type'), 'application/javascript; charset=utf-8');
    assert.equal(await status(adm, ingress + '/admin'), 200);
    const portalList = await get(adm, ingress + '/admin/api/portals', { ...ingressHeaders, Authorization: 'Bearer ' + token });
    assert.equal(portalList.status, 200);
    assert.deepEqual((await portalList.json()).portals, []);
    const createPortal = await fetch(`http://127.0.0.1:${adm}${ingress}/admin/api/portals`, { method: 'POST', headers: { ...ingressHeaders, Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: JSON.stringify({ slug: 'ingress-site', title: 'Ingress site' }) });
    assert.equal(createPortal.status, 201);
    const portal = await createPortal.json();
    const makePublic = await fetch(`http://127.0.0.1:${adm}${ingress}/admin/api/portals/${portal.id}`, { method: 'PATCH', headers: { ...ingressHeaders, Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: JSON.stringify({ visibility: 'public' }) });
    assert.equal(makePublic.status, 200);
    const publish = await fetch(`http://127.0.0.1:${adm}${ingress}/admin/api/portals/${portal.id}/html-projects`, { method: 'POST', headers: { ...ingressHeaders, Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: JSON.stringify({ folder: 'ingress-site', title: 'Ingress site' }) });
    assert.equal(publish.status, 201);
    const project = await publish.json();
    const site = await get(adm, ingress + project.url, ingressHeaders);
    assert.equal(site.status, 200);
    assert.equal(await site.text(), '<h1>Ingress site works</h1>');
    assert.equal(await status(adm, project.url), 404);
    assert.equal(await status(pub, project.url), 200);
    assert.equal(await status(adm, ingress + '/admin/api/portals', { 'X-Ingress-Path': '/api/hassio_ingress/../escape' }), 404);
    assert.equal(await status(adm, '/', ingressHeaders), 200);
    assert.equal((await get(adm, '/')).headers.get('content-type').includes('text/html'), true);
    assert.equal(await status(pub, '/api/v1/portals'), 200);
    console.log('PASS ingress isolation and HA-prefixed routes: UI, assets, authenticated API and root');
  } finally { await stopChild(child); fs.rmSync(dir, { recursive: true, force: true }) }
})().catch(e => { console.error(e); process.exitCode = 1 });
